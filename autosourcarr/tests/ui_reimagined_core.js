'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = path.join(__dirname, '../app/static/reimagined-core.js');
assert.ok(fs.existsSync(source), 'The Reimagined route and coverage module must exist');
const {parseRoute, chapterProgress, summarizeHealth} = require(source);

assert.deepEqual(parseRoute('#/wanted'), {tab:'subbed', scope:'missing_downloads'});
assert.deepEqual(parseRoute('#/wanted/sources'), {tab:'subbed', scope:'source_gaps'});
assert.deepEqual(parseRoute('#/wanted/verification'), {tab:'subbed', scope:'verification'});
assert.deepEqual(parseRoute('#/series/monitored'), {tab:'subbed', scope:'monitored'});
assert.deepEqual(parseRoute('#/catalog'), {tab:'subbed', scope:'catalog'});
assert.deepEqual(parseRoute('#/activity/repairs'), {tab:'tasks', section:'repairs'});
assert.deepEqual(parseRoute('#/sources/health'), {tab:'sources', section:'health'});
assert.deepEqual(parseRoute('#/sources'), {tab:'sources'}, 'The root source route must preserve the saved subtab');
assert.deepEqual(parseRoute('#/statistics'), {tab:'statistics'});
assert.deepEqual(parseRoute('#/settings/configuration'), {tab:'settings', section:'configuration'});
assert.equal(parseRoute('#/maintenance/reset-database'), null, 'Routes cannot replay mutations');
assert.equal(parseRoute('#/series/<img>'), null, 'Untrusted fragments cannot become selectors');
assert.deepEqual(chapterProgress(null), {downloaded:null, total:null, percent:null, complete:false});
assert.deepEqual(chapterProgress({chapter_count:null, downloaded_chapter_count:0}), {downloaded:0,total:null,percent:null,complete:false});
assert.equal(chapterProgress({chapter_count:0, downloaded_chapter_count:0}).complete, false, 'An empty title is not fully downloaded');
assert.equal(chapterProgress({chapter_count:100, downloaded_chapter_count:25}).percent, 25);
assert.equal(chapterProgress({chapter_count:100, downloaded_chapter_count:101}).percent, 100);
assert.equal(chapterProgress({chapter_count:100, downloaded_chapter_count:101}).complete, true);
const missing = summarizeHealth({library:{ok:false}, stats:{catalog:{entries:10}}});
assert.equal(missing.subscribed, null, 'Unavailable library metrics must not look like zero');
assert.equal(missing.matchedPercent, null, 'Missing matching evidence must not imply no matches');
const known = summarizeHealth({library:{ok:true,subbed_entries:0,downloaded_chapters:0}, stats:{catalog:{entries:20,matched_entries:15},sources:{enabled_families:5}}});
assert.equal(known.subscribed, 0);
assert.equal(known.matchedPercent, 75);
assert.equal(known.sources, 5);
console.log('Reimagined: safe navigation and truthful coverage/statistics passed');
