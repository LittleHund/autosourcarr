#!/usr/bin/env node
// Generates the typed UI client for /api/v1 from the OpenAPI document the .NET host produces.
//
//   dotnet run --project tests/AutoSourcarr.Tests -- --write-openapi api/openapi.json
//   node scripts/generate-api-client.mjs [--check] [openapi.json] [api-client.js]
//
// No dependencies. Output is deterministic so CI can regenerate and diff it (--check exits 1 on drift).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const args = process.argv.slice(2);
const check = args[0] === '--check';
if (check) args.shift();
const input = resolve(args[0] ?? 'api/openapi.json');
const output = resolve(args[1] ?? 'autosourcarr/app/static/generated/api-client.js');

const spec = JSON.parse(readFileSync(input, 'utf8'));
const schemas = spec.components?.schemas ?? {};
const lines = [];
const emit = line => lines.push(line);

function typeOf(schema) {
  if (!schema || schema === true) return '*';
  if (schema.$ref) return schema.$ref.split('/').pop();
  let types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  const nullable = types.includes('null');
  types = types.filter(t => t !== 'null');
  let base;
  if (schema.enum) base = schema.enum.map(v => JSON.stringify(v)).join('|');
  else if (types.length !== 1) base = types.length ? types.map(t => typeOf({ ...schema, type: t })).join('|') : '*';
  else switch (types[0]) {
    case 'string': base = 'string'; break;
    case 'integer': case 'number': base = 'number'; break;
    case 'boolean': base = 'boolean'; break;
    case 'array': base = `Array<${typeOf(schema.items)}>`; break;
    case 'object':
      if (schema.properties) {
        base = '{' + Object.entries(schema.properties).map(([name, value]) =>
          `${name}${(schema.required ?? []).includes(name) ? '' : '?'}: ${typeOf(value)}`).join(', ') + '}';
      } else base = `Object<string, ${typeOf(schema.additionalProperties)}>`;
      break;
    default: base = '*';
  }
  return nullable ? `(${base}|null)` : base;
}

emit('// GENERATED by scripts/generate-api-client.mjs from api/openapi.json. Do not edit by hand;');
emit('// CI regenerates this file and fails when it differs from the committed copy.');
emit(`// ${spec.info?.title ?? 'API'} contract version ${spec.info?.version ?? '?'}`);
emit('(function (global) {');
emit("  'use strict';");
emit('');
for (const name of Object.keys(schemas).sort()) {
  const schema = schemas[name];
  emit('  /**');
  emit(`   * @typedef {Object} ${name}`);
  for (const [prop, value] of Object.entries(schema.properties ?? {})) {
    const optional = !(schema.required ?? []).includes(prop);
    emit(`   * @property {${typeOf(value)}} ${optional ? `[${prop}]` : prop}`);
  }
  emit('   */');
  emit('');
}

emit('  /** Thrown for any non-2xx answer; `status` and the parsed `body` (when JSON) are kept. */');
emit('  class ApiError extends Error {');
emit('    constructor(status, body) {');
emit("      super((body && body.detail) || ('HTTP ' + status));");
emit("      this.name = 'ApiError';");
emit('      this.status = status;');
emit('      this.body = body;');
emit('    }');
emit('  }');
emit('');
emit('  /**');
emit('   * Either give `request(path, options)` (the app\'s own request helper: auth, timeouts, errors; it gets');
emit('   * `method`, a JSON `body` string and any per-call options) or let the client use `fetch` itself.');
emit('   * @param {{request?: (path: string, options: Object) => Promise<*>, adminToken?: (() => string)|string, baseUrl?: string, fetch?: typeof fetch}} [options]');
emit('   */');
emit('  function createClient(options) {');
emit('    const settings = options || {};');
emit("    const base = settings.baseUrl || '';");
emit("    const token = () => typeof settings.adminToken === 'function' ? settings.adminToken() : (settings.adminToken || '');");
emit('    async function call(method, path, body, extra) {');
emit('      const callOptions = extra || {};');
emit('      const json = body === undefined ? undefined : JSON.stringify(body);');
emit('      if (settings.request) return settings.request(base + path, { ...callOptions, method, body: json });');
emit('      const send = settings.fetch || global.fetch.bind(global);');
emit("      const headers = { Accept: 'application/json' };");
emit('      const admin = token();');
emit("      if (admin) headers['X-Admin-Token'] = admin;");
emit("      if (json !== undefined) headers['Content-Type'] = 'application/json';");
emit("      const response = await send(base + path, { method, headers, body: json, signal: callOptions.signal, credentials: 'same-origin' });");
emit("      const text = await response.text();");
emit('      let parsed = null;');
emit('      if (text) { try { parsed = JSON.parse(text); } catch (_) { parsed = text; } }');
emit('      if (!response.ok) throw new ApiError(response.status, parsed);');
emit('      return parsed;');
emit('    }');
emit('    return {');

const operations = [];
for (const path of Object.keys(spec.paths ?? {}).sort()) {
  for (const method of Object.keys(spec.paths[path]).sort()) {
    operations.push({ path, method, operation: spec.paths[path][method] });
  }
}
operations.sort((a, b) => a.operation.operationId.localeCompare(b.operation.operationId));
for (const { path, method, operation } of operations) {
  const params = (operation.parameters ?? []).filter(p => p.in === 'path').map(p => p.name);
  const success = Object.entries(operation.responses ?? {}).find(([code]) => code.startsWith('2'));
  const schema = success?.[1]?.content?.['application/json']?.schema;
  const returns = schema ? typeOf(schema) : 'null';
  const hasBody = Boolean(operation.requestBody);
  const bodySchema = operation.requestBody?.content?.['application/json']?.schema;
  emit('      /**');
  if (operation.summary) emit(`       * ${operation.summary}`);
  emit(`       * ${method.toUpperCase()} ${path}`);
  for (const p of params) emit(`       * @param {string} ${p}`);
  if (hasBody) emit(`       * @param {${typeOf(bodySchema)}} body`);
  emit('       * @param {{signal?: AbortSignal}} [options] per-call options, passed through to `request`');
  emit(`       * @returns {Promise<${returns}>}`);
  emit('       */');
  const signature = [...params, ...(hasBody ? ['body'] : []), 'options'].join(', ');
  const url = params.length
    ? '`' + path.replace(/\{([^}]+)\}/g, (_, name) => '${encodeURIComponent(' + name + ')}') + '`'
    : `'${path}'`;
  emit(`      ${operation.operationId}(${signature}) { return call('${method.toUpperCase()}', ${url}, ${hasBody ? 'body' : 'undefined'}, options); },`);
}
emit('    };');
emit('  }');
emit('');
emit('  global.AutoSourcarrApi = Object.freeze({ createClient, ApiError });');
emit("})(typeof window !== 'undefined' ? window : globalThis);");
const text = lines.join('\n') + '\n';

if (check) {
  const current = existsSync(output) ? readFileSync(output, 'utf8') : '';
  if (current !== text) {
    console.error(`::error file=${args[1] ?? 'autosourcarr/app/static/generated/api-client.js'}::The generated API client is out of date; run scripts/generate-api-client.mjs and commit it.`);
    process.exit(1);
  }
  console.log('API client is up to date.');
} else {
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, text);
  console.log('Wrote ' + output);
}
